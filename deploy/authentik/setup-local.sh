#!/bin/sh
set -eu

cd "$(dirname "$0")"
if [ -e .env ]; then
  printf '%s\n' 'Refusing to overwrite existing deploy/authentik/.env.' >&2
  exit 1
fi
umask 077
pg_pass=$(openssl rand -base64 36 | tr -d '\n')
secret_key=$(openssl rand -base64 60 | tr -d '\n')
printf 'PG_PASS=%s\nAUTHENTIK_SECRET_KEY=%s\nPORTAL_TEST_EXTERNAL_HOST=\nPORTAL_BOOKS_EXTERNAL_HOST=\nPORTAL_AUDIOBOOKSHELF_EXTERNAL_HOST=\nPORTAL_AUDIOBOOKSHELF_OIDC_CLIENT_SECRET=\nPORTAL_AUDIOBOOKSHELF_OIDC_WEB_CALLBACK_URL=\nPORTAL_AUDIOBOOKSHELF_OIDC_GATEWAY_CALLBACK_URL=\nPORTAL_AUDIOBOOKSHELF_OIDC_MOBILE_CALLBACK_URL=\nPORTAL_AUDIOBOOKSHELF_OIDC_LOGOUT_CALLBACK_URL=\nPORTAL_METRICS_EXTERNAL_HOST=\nPORTAL_TRANSMISSION_EXTERNAL_HOST=\nPORTAL_TRANSMISSION_RPC_USERNAME=\nPORTAL_TRANSMISSION_RPC_PASSWORD=\nPORTAL_STATUS_UPSTREAM_URL=\nPORTAL_IMMICH_OIDC_CLIENT_SECRET=\nPORTAL_IMMICH_OIDC_WEB_LOGIN_CALLBACK_URL=\nPORTAL_IMMICH_OIDC_WEB_LINK_CALLBACK_URL=\nPORTAL_IMMICH_OIDC_LAN_LOGIN_CALLBACK_URL=\nPORTAL_IMMICH_OIDC_LAN_LINK_CALLBACK_URL=\nPORTAL_IMMICH_OIDC_TAILNET_LOGIN_CALLBACK_URL=\nPORTAL_IMMICH_OIDC_TAILNET_LINK_CALLBACK_URL=\nPORTAL_IMMICH_OIDC_MOBILE_CALLBACK_URL=\n' "$pg_pass" "$secret_key" > .env
unset pg_pass secret_key
printf '%s\n' 'Created deploy/authentik/.env with random secrets (file mode 600).'
printf '%s\n' 'The file is ignored by Git. Do not share or commit it.'
